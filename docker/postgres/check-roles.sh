#!/bin/sh
# Checks the production database permissions in the db container, after migrations have run:
#   docker compose --env-file .env.production exec db sh /provision/check-roles.sh
# Exits non-zero if training_app can truncate or create tables, or can't write to a table made later by the owner.
set -u

status=0
app() {
  PGPASSWORD="$TRAINING_APP_DB_PASSWORD" psql --no-psqlrc --quiet --tuples-only --no-align -v ON_ERROR_STOP=1 \
    --host 127.0.0.1 --username training_app --dbname "$POSTGRES_DB" --command "$1" 2>&1
}
owner() {
  PGPASSWORD="$TRAINING_OWNER_DB_PASSWORD" psql --no-psqlrc --quiet --tuples-only --no-align -v ON_ERROR_STOP=1 \
    --host 127.0.0.1 --username training_owner --dbname "$POSTGRES_DB" --command "$1" 2>&1
}
pass() { echo "ok: $1"; }
fail() { echo "FAILED: $1"; [ -n "${2:-}" ] && echo "  $2"; status=1; }
refused() {
  output=$(app "$2")
  case "$output" in
    *"permission denied"*|*"must be owner"*) pass "$1 is refused" ;;
    *) fail "$1 was not refused" "$output" ;;
  esac
}
expect() {
  output=$(app "$3")
  if [ "$output" = "$2" ]; then pass "$1"; else fail "$1" "expected '$2', got '$output'"; fi
}

refused "TRUNCATE as training_app" "BEGIN; TRUNCATE django_session; ROLLBACK;"
refused "CREATE TABLE as training_app" "CREATE TABLE role_check_app (id integer);"
expect "training_app isn't a member of training_owner" "f" \
  "SELECT pg_has_role('training_app', 'training_owner', 'MEMBER');"
expect "training_owner owns every table" "0" \
  "SELECT count(*) FROM pg_tables WHERE schemaname = 'public' AND tableowner <> 'training_owner';"
expect "training_app can read and write every table" "0" \
  "SELECT count(*) FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relkind IN ('r', 'p')
   AND NOT (has_table_privilege('training_app', oid, 'SELECT') AND has_table_privilege('training_app', oid, 'INSERT')
            AND has_table_privilege('training_app', oid, 'UPDATE') AND has_table_privilege('training_app', oid, 'DELETE'));"
# A comma-separated list is true when any one privilege is held, which is what this check wants.
expect "training_app has no TRUNCATE, REFERENCES or TRIGGER on any table" "0" \
  "SELECT count(*) FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relkind IN ('r', 'p')
   AND has_table_privilege('training_app', oid, 'TRUNCATE, REFERENCES, TRIGGER');"

# A table created after provisioning, as a later migration would, through the default privileges.
created=$(owner "CREATE TABLE role_check_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note text);")
if [ -n "$created" ]; then
  fail "training_owner can create a table" "$created"
else
  expect "training_app can insert into a table created later" "1" \
    "INSERT INTO role_check_probe (note) VALUES ('check') RETURNING id;"
  expect "training_app can delete from a table created later" "" "DELETE FROM role_check_probe;"
  owner "DROP TABLE role_check_probe;" >/dev/null || fail "dropping role_check_probe"
fi

exit "$status"
